def build_process_case(industry_key: str, source: dict) -> dict:
    """Build a practical, clearly simulated case linked to a catalog process."""
    case = deepcopy(PROCESS_CASES.get(industry_key, {}).get(source["code"]))
    if case is None:
        # New processes can be added to the catalog before a bespoke walkthrough
        # is written. Keep the reference library usable and clearly mark the
        # generated scenario as an editable simulation instead of failing the
        # whole catalog response.
        case = {
            "title": f"{source['name']}授权、执行与异常闭环演练",
            "scenario": (
                f"围绕{source['name']}选取一项正常业务和一项异常/例外业务，"
                "验证申请、授权、执行、复核、记录和升级是否形成可重演链路。"
            ),
            "sample_plan": (
                f"取得{source['population']}完整总体，按金额、风险、期间和异常标识分层；"
                "优先检查无授权、手工修改、跨期、重复和未关闭例外，样本小则全查。"
            ),
            "exception_criteria": (
                "关键步骤缺少授权或同期记录；执行人与复核人未分离；业务数据与原始凭证/"
                "系统日志无法勾稽；异常没有责任人、期限、升级和复核结论。"
            ),
            "root_cause": (
                f"访谈{source['name']}的申请、执行和复核岗位，走查系统权限与台账字段，"
                "区分人员培训、流程设计、系统校验、数据接口和监督频率等根因。"
            ),
            "actions": [
                "先保全原始记录并对异常交易/事项做影响评估，不用事后补写替代缺失的同期事实。",
                f"将{source['name']}的申请、执行、复核、异常和证据要求写入流程配置，明确岗位分离和升级时限。",
                "按风险设置异常台账、责任人和到期日，整改后由未参与执行的人员复核并重测。",
            ],
            "retest": (
                f"抽取整改后{source['population']}，追查申请、授权、执行、复核和异常处置；"
                "必要时用一笔受控测试事项验证系统阻断、告警和审计日志。"
            ),
        }
    case.update({
        "kind": "simulated",
        "process_code": source["code"],
        "process_name": source["name"],
        "risk": source["risk"],
        "objective": source["objective"],
        "population": source["population"],
        "test_program": source["test"],
        "evidence": source["evidence"],
        "finding_example": f"{case['exception_criteria']} 请在实际执行时记录样本编号、原始事实、适用标准和影响范围，不要将本模拟情境直接登记为真实发现。",
        "owner": "对应流程负责人牵头；控制执行人提供原始记录；内控协调人跟踪；独立复核人验证。",
        "closure_criteria": "整改证据真实且可复演；复核人与责任人分离；独立重测覆盖失败原因和足够运行周期；重测通过并完成关闭批准。",
    })
    return case


def get_process_case(industry_key: str, source: dict) -> dict:
    """Return a copy of the bespoke or generated case for a catalog process."""
    return build_process_case(industry_key, source)

